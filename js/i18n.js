export function T(lang, key) {
  return DICT[lang]?.[key] ?? DICT.ja[key] ?? '';
}

/** データ側の {ja, easy, en} から言語を選ぶ。easy が無ければ ja に落とす。 */
export function pick(obj, lang) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[lang] || obj.ja || obj.en || '';
}
